const has = (v: unknown): v is string => typeof v === 'string' && v.trim() !== '';

// Merge translated name/note over a {name, note} array, element by element.
function mergeNotes(
  en: { name: string; note: string }[] | undefined,
  tr: { name?: string; note?: string }[] | undefined,
): { name: string; note: string }[] | undefined {
  if (!en || !tr) return en;
  return en.map((el, i) => ({
    name: has(tr[i]?.name) ? (tr[i]!.name as string) : el.name,
    note: has(tr[i]?.note) ? (tr[i]!.note as string) : el.note,
  }));
}

// Merge translated title/note over furtherReading, preserving author + year.
function mergeReading(
  en: ExerciseExtras['furtherReading'],
  tr: { title?: string; note?: string }[] | undefined,
): ExerciseExtras['furtherReading'] {
  if (!en || !tr) return en;
  return en.map((el, i) => ({
    ...el,
    title: has(tr[i]?.title) ? (tr[i]!.title as string) : el.title,
    note: has(tr[i]?.note) ? (tr[i]!.note as string) : el.note,
  }));
}

export function localizeExtras(
  slug: string,
  extras: ExerciseExtras,
  locale: Locale,
): ExerciseExtras {
  if (locale === 'en') return extras;
  const tr = EXERCISE_EXTRAS_I18N[slug]?.[locale];
  if (!tr) return extras;
  // commonPitfalls (a string[]) is used wholesale only when fully present —
  // a complete array with no empty holes — otherwise fall back to English.
  const pitfallsOk =
    Array.isArray(tr.commonPitfalls) &&
    tr.commonPitfalls.length === (extras.commonPitfalls?.length ?? -1) &&
    tr.commonPitfalls.every(has);
  return {
    ...extras,
    longerAbout: has(tr.longerAbout) ? tr.longerAbout : extras.longerAbout,
    workedExample: has(tr.workedExample) ? tr.workedExample : extras.workedExample,
    commonPitfalls: pitfallsOk ? tr.commonPitfalls : extras.commonPitfalls,
    relatedThinkers: mergeNotes(extras.relatedThinkers, tr.relatedThinkers),
    furtherReading: mergeReading(extras.furtherReading, tr.furtherReading),
    kindredPractices: mergeNotes(extras.kindredPractices, tr.kindredPractices),
  };
}
