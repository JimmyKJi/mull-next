/** Look up the translated narration fragments for one dimension. Returns
 *  undefined when the dim/locale has no entry (caller falls back to the
 *  English DIM_NARRATIONS source). */
export function getLocalizedDimNarration(
  key: string,
  locale: Locale,
): DimNarrationI18nFields | undefined {
  return DIM_NARRATION_I18N[key]?.[locale];
}

// Degree qualifiers, per locale. Hand-maintained (tiny, closed set). The
// three buckets correspond to distance from the scale midpoint:
//   strong   — 3+ away   ("strongly")
//   moderate — 1–3 away  ("moderately")
//   barely   — <1 away   ("just barely")
//
// Only locales present here use the prefix template; anything missing
// falls through to the English splice in poleSentence(). en is included
// for completeness but the English path doesn't read it.
export type NarrationQualifiers = { strong: string; moderate: string; barely: string };

export const NARRATION_QUALIFIERS: Partial<Record<Locale, NarrationQualifiers>> = {
  en: { strong: 'strongly', moderate: 'moderately', barely: 'just barely' },
  zh: { strong: '强烈地', moderate: '较为', barely: '略微' },
};
