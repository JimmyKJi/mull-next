// Translations of the 16-dimension narration fragments in
// lib/dim-narration.ts (DIM_NARRATIONS), keyed by dim key → locale →
// { label, high, low }. Used by /compare to render each user's stance
// on the dimensions where they most diverge / converge.
//
// The English source builds its sentences by splicing a degree qualifier
// ("strongly", "moderately", "just barely") *after* the leading English
// verb of each fragment — grammar that doesn't carry to other languages.
// So for non-English locales poleSentence() switches to a simpler
// prefix template: qualifier + fragment. The fragments here are therefore
// translated as standalone verb-phrases that read naturally with a
// prefixed adverb (zh: "强烈地" + "认为苦难是根本的").
//
// The DIM_NARRATION_I18N block between the sentinels is GENERATED by
// scripts/translate-content.mjs — don't hand-edit inside them. The type,
// the qualifier table, and the getLocalizedDimNarration helper below are
// hand-maintained. English is the source (lives in DIM_NARRATIONS), so a
// missing locale/field falls back to English at the call site.

