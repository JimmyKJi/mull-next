// Generator-managed CONTENT translations for the ten archetype arcs
// (and their per-flavor enrollment lenses), filled by
// scripts/translate-content.mjs into the single managed region below.
// One entry per archetype key, mirroring PILGRIMAGE_ARCS. Translatable
// fields per arc:
//   • spirit          — the one-line shape of the 30-day arc
//   • welcomeDefault   — the enrollment welcome paragraph
//   • phases           — the three ten-day phase names (string[])
//   • days             — the 30 (pilgrim: 31) day cards, by index;
//                        each: title, framing, prompt, expect
//   • lens             — the per-flavor enrollment lenses, a
//                        Record<DimKey,string> (the script merges
//                        FLAVOR_LENSES[key] in under this synthetic
//                        field so one pass covers arcs + lenses)
//
// The enrollment/scoring/state logic stays in lib/pilgrimage.ts and is
// never translated — only the prose passes through here.
// localizePilgrimageArc / getEnrollmentMessageLocalized merge a
// locale's overlay onto the English source with per-field fallback, so
// a missing or partial translation degrades to English rather than
// blanking the page.
//
// Do not hand-edit inside the BEGIN/END gen-translate sentinels:
// re-running scripts/translate-content.mjs rewrites that region.

