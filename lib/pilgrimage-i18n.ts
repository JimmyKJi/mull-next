const has = (v: unknown): v is string =>
  typeof v === 'string' && v.trim() !== '';

/** Localize a whole arc: returns the English arc with any
 *  locale-present fields overlaid, falling back per-field. Indexing the
 *  overlay by the RESOLVED arc key (getPilgrimageArc falls back to
 *  cartographer for unknown keys) keeps the overlay lookup aligned with
 *  the arc actually rendered. */
export function localizePilgrimageArc(
  archetypeKey: string,
  locale: Locale,
): PilgrimageArc {
  const base = getPilgrimageArc(archetypeKey);
  if (locale === 'en') return base;
  const ov = PILGRIMAGE_I18N[base.archetypeKey]?.[locale];
  if (!ov) return base;
  return {
    ...base,
    spirit: has(ov.spirit) ? ov.spirit : base.spirit,
    welcomeDefault: has(ov.welcomeDefault)
      ? ov.welcomeDefault
      : base.welcomeDefault,
    phases: base.phases.map((p, i) => {
      const tv = ov.phases?.[i];
      return has(tv) ? tv : p;
    }) as [string, string, string],
    days: base.days.map((d, i) => {
      const td = ov.days?.[i];
      if (!td) return d;
      return {
        ...d,
        title: has(td.title) ? td.title : d.title,
        framing: has(td.framing) ? td.framing : d.framing,
        prompt: has(td.prompt) ? td.prompt : d.prompt,
        expect: has(td.expect) ? td.expect : d.expect,
      };
    }),
  };
}

/** Localized enrollment message: the per-flavor lens if one exists for
 *  this (archetype, flavor) in `locale`, else the localized welcome
 *  default, else the English behavior (lens-or-default). */
export function getEnrollmentMessageLocalized(
  archetypeKey: string,
  flavor: DimKey | null,
  locale: Locale,
): string {
  const base = getPilgrimageArc(archetypeKey);
  if (locale !== 'en') {
    const ov = PILGRIMAGE_I18N[base.archetypeKey]?.[locale];
    const lensVal = flavor ? ov?.lens?.[flavor] : undefined;
    if (has(lensVal)) return lensVal;
    if (has(ov?.welcomeDefault)) return ov.welcomeDefault;
  }
  return getEnrollmentMessage(archetypeKey, flavor);
}
