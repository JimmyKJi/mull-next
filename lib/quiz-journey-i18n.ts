const has = (v: unknown): v is string => typeof v === 'string' && v.trim() !== '';

/** Localize one scene. Per-field fallback to English: any field the
 *  overlay is missing (or that came back blank) keeps its English
 *  value, so a partial translation never blanks the screen. */
export function localizeScene(scene: JourneyScene, locale: Locale): JourneyScene {
  if (locale === 'en') return scene;
  const tr = JOURNEY_SCENES_I18N[scene.id]?.[locale];
  if (!tr) return scene;

  if (scene.kind === 'frame') {
    return {
      ...scene,
      eyebrow: has(tr.eyebrow) ? tr.eyebrow : scene.eyebrow,
      body: has(tr.body) ? tr.body : scene.body,
      advance: has(tr.advance) ? tr.advance : scene.advance,
    };
  }

  if (scene.kind === 'reveal') {
    return {
      ...scene,
      eyebrow: has(tr.eyebrow) ? tr.eyebrow : scene.eyebrow,
      coldOpen: has(tr.coldOpen) ? tr.coldOpen : scene.coldOpen,
    };
  }

  // chamber
  const choices = scene.choices.map((c, i) => {
    const txt = tr.choices?.[i]?.text;
    return has(txt) ? { ...c, text: txt } : c;
  });

  let choiceEpilogues = scene.choiceEpilogues;
  if (scene.choiceEpilogues) {
    const merged: Record<number, string> = {};
    for (const [k, v] of Object.entries(scene.choiceEpilogues)) {
      const tv = tr.choiceEpilogues?.[k];
      merged[+k] = has(tv) ? tv : v;
    }
    choiceEpilogues = merged;
  }

  return {
    ...scene,
    eyebrow: has(tr.eyebrow) ? tr.eyebrow : scene.eyebrow,
    body: has(tr.body) ? tr.body : scene.body,
    prompt: has(tr.prompt) ? tr.prompt : scene.prompt,
    epilogue: has(tr.epilogue) ? tr.epilogue : scene.epilogue,
    twistClue: has(tr.twistClue) ? tr.twistClue : scene.twistClue,
    choices,
    choiceEpilogues,
  };
}

/** Localize one reveal ending. flavorDetails merges per-DimKey onto
 *  the English source so an untranslated flavor beat still renders
 *  (in English) rather than vanishing. */
export function localizeReveal(ending: RevealEnding, locale: Locale): RevealEnding {
  if (locale === 'en') return ending;
  const tr = JOURNEY_REVEALS_I18N[ending.archetypeKey]?.[locale];
  if (!tr) return ending;

  let flavorDetails = ending.flavorDetails;
  if (tr.flavorDetails) {
    const merged: Partial<Record<DimKey, string>> = { ...ending.flavorDetails };
    for (const [k, v] of Object.entries(tr.flavorDetails)) {
      if (has(v)) merged[k as DimKey] = v;
    }
    flavorDetails = merged;
  }

  return {
    ...ending,
    recognition: has(tr.recognition) ? tr.recognition : ending.recognition,
    flavorDetails,
    flavorDetailDefault: has(tr.flavorDetailDefault)
      ? tr.flavorDetailDefault
      : ending.flavorDetailDefault,
    inheritance: has(tr.inheritance) ? tr.inheritance : ending.inheritance,
    ask: has(tr.ask) ? tr.ask : ending.ask,
    advance: has(tr.advance) ? tr.advance : ending.advance,
  };
}

/** Localize the whole reveals map — convenience for passing a
 *  fully-localized Record into the (client) engine as a prop. */
export function localizeReveals(
  reveals: Record<string, RevealEnding>,
  locale: Locale,
): Record<string, RevealEnding> {
  if (locale === 'en') return reveals;
  const out: Record<string, RevealEnding> = {};
  for (const [k, v] of Object.entries(reveals)) out[k] = localizeReveal(v, locale);
  return out;
}
