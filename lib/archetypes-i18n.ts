/** Overlay translated fields onto an Archetype for the given locale.
 *  Falls back to English for any missing field or locale. */
export function localizeArchetype(a: Archetype, locale: Locale): Archetype {
  if (locale === 'en') return a;
  const o = ARCHETYPES_I18N[a.key]?.[locale];
  if (!o) return a;
  return {
    ...a,
    spirit: o.spirit ?? a.spirit,
    detailedAbout: o.detailedAbout ?? a.detailedAbout,
    whatItGetsRight: o.whatItGetsRight ?? a.whatItGetsRight,
    whereItFalters: o.whereItFalters ?? a.whereItFalters,
    dayInTheLife: o.dayInTheLife ?? a.dayInTheLife,
    quotes: a.quotes.map((q, i) =>
      o.quotes?.[i]?.text ? { ...q, text: o.quotes[i]!.text! } : q
    ),
    readingList: a.readingList.map((r, i) =>
      o.readingList?.[i]?.note ? { ...r, note: o.readingList[i]!.note! } : r
    ),
    tensions: a.tensions.map((tn, i) =>
      o.tensions?.[i]?.spark ? { ...tn, spark: o.tensions[i]!.spark! } : tn
    ),
    modernExemplars: a.modernExemplars.map((m, i) => {
      const tr = o.modernExemplars?.[i];
      return tr ? { ...m, role: tr.role ?? m.role, note: tr.note ?? m.note } : m;
    }),
    commonMistakes: a.commonMistakes.map((c, i) => {
      const tr = o.commonMistakes?.[i];
      return tr
        ? { ...c, mistake: tr.mistake ?? c.mistake, antidote: tr.antidote ?? c.antidote }
        : c;
    }),
  };
}
