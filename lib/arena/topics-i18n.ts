/** Overlay translated fields onto an ArenaTopic for the given locale.
 *  Keyed by slug. Falls back to English per field. */
export function localizeArenaTopic(topic: ArenaTopic, locale: Locale): ArenaTopic {
  if (locale === "en") return topic;
  const o = ARENA_TOPICS_I18N[topic.slug]?.[locale];
  if (!o) return topic;
  return {
    ...topic,
    title: o.title ?? topic.title,
    prompt: o.prompt ?? topic.prompt,
    primer: o.primer ?? topic.primer,
  };
}
